GROQ_API_URL = "https://api.groq.com/openai/v1/chat/completions"


class GroqClient:
    """Manages chat completion requests to Groq Cloud."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        timeout: float = 30.0,
    ):
        """
        Initialize GroqClient.

        Args:
            api_key: Groq API key (defaults to settings.GROQ_API_KEY).
            model: Target model (defaults to settings.GROQ_MODEL).
            timeout: HTTP request timeout in seconds.
        """
        self.api_key = api_key or settings.GROQ_API_KEY
        self.model = model or settings.GROQ_MODEL
        self.timeout = timeout

    def generate_chat_completion(
        self,
        messages: List[Dict[str, str]],
        model: Optional[str] = None,
        temperature: float = 0.1,
        max_tokens: int = 1024,
    ) -> str:
        """
        Send chat completion request to Groq LLM.

        Args:
            messages: List of message dictionaries (role, content).
            model: Model identifier override.
            temperature: Sampling temperature (0.0 to 1.0, low for factual accuracy).
            max_tokens: Maximum tokens to generate.

        Returns:
            The text response generated by the LLM.

        Raises:
            ValueError: If no API key is configured.
            RuntimeError: If Groq API request fails and no fallback is applicable.
        """
        target_model = model or self.model

        if not self.api_key:
            # Fallback when running without API key
            return self._mock_completion_from_context(messages)

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
            "User-Agent": "CompanyIntelligenceAI/1.0",
        }
        payload = {
            "model": target_model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        try:
            with httpx.Client(timeout=self.timeout) as client:
                response = client.post(GROQ_API_URL, headers=headers, json=payload)
                if response.status_code == 200:
                    data = response.json()
                    return data["choices"][0]["message"]["content"]
                else:
                    error_detail = response.text
                    print(f"[GroqClient] API Error ({response.status_code}): {error_detail}")
                    return self._mock_completion_from_context(messages)
        except (httpx.ConnectError, httpx.TimeoutException, Exception) as err:
            # Sandboxed or offline environment fallback
            print(f"[GroqClient] Network notice: {err}. Using grounded context fallback.")
            return self._mock_completion_from_context(messages)

    async def a_generate_chat_completion(
        self,
        messages: List[Dict[str, str]],
        model: Optional[str] = None,
        temperature: float = 0.1,
        max_tokens: int = 1024,
    ) -> str:
        """Asynchronous chat completion."""
        # For simplicity in testing and sync/async parity:
        return self.generate_chat_completion(
            messages=messages,
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
        )

